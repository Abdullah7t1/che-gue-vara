export function isGoldAsset(asset: Pick<Asset, 'symbol' | 'tvSymbol'>): boolean {
  const s = `${asset.symbol} ${asset.tvSymbol}`.toUpperCase();
  return s.includes('XAU') || s.includes('GOLD') || s.includes('PAXG') || s.includes('GC=F');
}
